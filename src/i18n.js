let lang = 'tr';

export const LANGS = { tr: 'Türkçe', ar: 'العربية' };

export function setLang(l) {
  lang = STRINGS[l] ? l : 'tr';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
}

export const getLang = () => lang;

/** Number locale: Arabic UI still uses Latin digits, which matches TKGM documents. */
export const numberLocale = () => (lang === 'ar' ? 'ar-u-nu-latn' : 'tr-TR');

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.tr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
